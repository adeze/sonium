#!/usr/bin/env python3
"""Render the QA manifest inventory used by the checked-in README link."""

from __future__ import annotations

import argparse
import pathlib
import sys
try:
    import tomllib
except ModuleNotFoundError:  # Python 3.10 and earlier
    import tomli as tomllib


ROOT = pathlib.Path(__file__).resolve().parents[1]
QA_ROOT = ROOT / "crates" / "sonium-qa"
MANIFEST = QA_ROOT / "validation-manifest.toml"
CARGO = QA_ROOT / "Cargo.toml"
OUTPUT = QA_ROOT / "manifest-inventory.md"


def cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def render() -> str:
    with MANIFEST.open("rb") as file:
        cases = tomllib.load(file)["case"]
    with CARGO.open("rb") as file:
        binaries = tomllib.load(file)["bin"]

    tiers: dict[str, int] = {}
    for case in cases:
        tiers[case["tier"]] = tiers.get(case["tier"], 0) + 1

    lines = [
        "# QA manifest inventory",
        "",
        "<!-- Generated by scripts/generate_qa_inventory.py; do not edit manually. -->",
        "",
        "This is the authoritative manifest view of release evidence. It lists",
        "validated cases, not every runnable QA binary.",
        "",
        "## Summary",
        "",
        f"- Registered Cargo QA binaries: {len(binaries)}",
        f"- Manifest-backed validation cases: {len(cases)}",
        "",
        "| Tier | Cases |",
        "| --- | ---: |",
    ]
    lines.extend(f"| {cell(tier)} | {count} |" for tier, count in sorted(tiers.items()))
    lines.extend(
        [
            "",
            "## Manifest-backed cases",
            "",
            "| ID | Owner | Binary | Tier | Method |",
            "| --- | --- | --- | --- | --- |",
        ]
    )
    for case in sorted(cases, key=lambda entry: entry["id"]):
        lines.append(
            "| {id} | {owner} | `{bin}` | {tier} | {method} |".format(
                id=cell(case["id"]),
                owner=cell(case["owner"]),
                bin=cell(case["bin"]),
                tier=cell(case["tier"]),
                method=cell(case["method"]),
            )
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="update the generated inventory")
    args = parser.parse_args()
    expected = render()
    actual = OUTPUT.read_text() if OUTPUT.exists() else ""
    if actual == expected:
        return 0
    if args.write:
        OUTPUT.write_text(expected)
        return 0
    print(
        f"{OUTPUT.relative_to(ROOT)} is stale; run "
        "python3 scripts/generate_qa_inventory.py --write",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
