/// Tetrahedralize a point cloud and return both mesh and quality diagnostics.
pub fn tetrahedralize_points_with_result(
    points: &[Point],
    config: &TetrahedralizeConfig,
) -> TetrahedralizationResult {
    let mesh = tetrahedralize_points(points, config);
    TetrahedralizationResult::from_mesh(mesh, None)
}

/// Strict point-cloud tetrahedralization with typed input and output checks.
///
/// [`tetrahedralize_points`] is retained as a compatibility API for callers
/// that intentionally accept an empty result for underspecified clouds. New
/// production code should use this fallible entry point: malformed, repeated,
/// non-finite, or coplanar input is rejected before the Delaunay kernel runs,
/// and generated connectivity is validated before it is returned.
pub fn tetrahedralize_points_checked(
    points: &[Point],
    config: &TetrahedralizeConfig,
) -> Result<TetrahedralizationResult, TetrahedralizationError> {
    validate_point_cloud(points)?;
    let result = tetrahedralize_points_with_result(points, config);
    if result.validity.is_valid() && result.mesh.num_elements() > 0 {
        Ok(result)
    } else {
        Err(TetrahedralizationError::InvalidMesh {
            diagnostics: Box::new(result.validity),
        })
    }
}

