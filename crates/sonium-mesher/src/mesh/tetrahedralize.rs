//! Tetrahedralisation engine for 3D mesh generation.
//!
//! # Status: Bowyer-Watson point clouds plus bounded surface recovery
//!
//! This module ships an unconstrained Bowyer-Watson kernel with:
//!
//! - **Exact-precision predicates** via Shewchuk's adaptive `robust::insphere`
//!   and `robust::orient3d`. Cocircular / coplanar inputs no longer corrupt
//!   topology under IEEE rounding.
//! - **Neighbour-graph adjacency** with stable slot indices and a free-list
//!   for vacated cavity tets. Insertion uses a visibility walk seeded from
//!   the previously inserted tet and a BFS over the neighbour graph to
//!   discover the cavity. Walk length is O(n^{1/3}) on average for spatially
//!   coherent input, so total insertion is roughly O(n^{4/3}); the previous
//!   linear-scan kernel was O(n²).
//! - Steiner-point insertion at circumcentres of poor-quality tets when
//!   [`TetrahedralizeConfig::add_interior_points`] is set.
//! - Volume-weighted Lloyd relaxation (interior nodes only).
//! - Laplacian smoothing of interior nodes.
//! - A diagnostic pass via [`validate_delaunay`] that flags zero-volume tets,
//!   non-Delaunay edges, and elements that escaped the super-tet filter.
//!
//! What it still does **not** cover:
//! - The complete Si / TetGen flip table for Steiner-free 3D constrained
//!   Delaunay recovery. `tetrahedralize_surface` uses the robust predicates
//!   below and a bounded Steiner subdivision pass to recover missing input
//!   edges and triangular boundary facets.
//! - Sliver exudation (weighted Delaunay). Slivers are detected but not
//!   actively removed; the Lloyd / Steiner / Laplacian post-passes only
//!   improve them on average.
//! - Hex / mixed-element meshing.
//!
//! # Constraint-recovery scope
//!
//! The flip table cannot perform every *in-plane diagonal swap*: the tet ring
//! around a coplanar edge is not necessarily strictly convex in projection.
//! Before edge subdivision, recovery therefore adopts any exact in-plane
//! Delaunay tiling of a requested facet (TetGen-style "facet = union of mesh
//! faces"). This prevents an otherwise valid annular cap or re-entrant
//! tube/wall cap from creating a Steiner cascade merely because its input
//! diagonals differ from the Delaunay triangulation.
//!
//! The remaining recovery sequence is flip-based edge/facet recovery (with
//! recovered constraint edges and faces protected), targeted Steiner splits
//! (at exact edge crossings, transversal facet pierce points, then stable
//! midpoint/centroid fallbacks), and Steiner suppression. Inputs that still
//! cannot converge within [`MAX_CONSTRAINT_RECOVERY_ROUNDS`] or the point work
//! cap return [`TetrahedralizationError::ConstraintRecoveryFailed`] with
//! missing constraints and operation counts. Re-entrant facet cavities use a
//! bounded local-Delaunay candidate path with exact boundary preservation;
//! larger cavities beyond that local work cap remain fail-closed.

