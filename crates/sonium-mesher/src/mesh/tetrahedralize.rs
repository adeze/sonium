/// Tetrahedralize a point cloud using incremental Delaunay.
///
/// The [`TetrahedralizeConfig`] fields are honoured as follows:
/// - `add_interior_points` + `max_ratio`: insert Steiner points at the
///   circumcentre of the worst tet (by `quality = r/l_min`) until every tet
///   meets `max_ratio` or a safety cap on the number of rounds is hit.
/// - `lloyd_iterations`: run that many rounds of volume-weighted Lloyd
///   relaxation on the interior nodes after the Delaunay completes.
/// - `max_smooth_iterations`: classic Laplacian smoothing afterwards.
/// - `preserve_surface`: meaningful only for [`tetrahedralize_surface`],
///   where explicit facets are available.
pub fn tetrahedralize_points(points: &[Point], config: &TetrahedralizeConfig) -> Mesh {
    let working_points = points_with_quality_steiner(points, config);
    let (nodes, elements) = run_delaunay(&working_points);
    let mut mesh = mesh_from_tets(nodes, elements);
    postprocess_mesh(&mut mesh, config);
    mesh
}

/// Tetrahedralize from a point set, optionally tagging detected boundary faces.
///
/// When `surface_facets` is non-empty and `config.preserve_surface` is set,
/// the initial Bowyer-Watson mesh is followed by bounded boundary recovery:
/// missing constrained edges are split (at the exact crossing with the
/// blocking Delaunay edge when one exists, else at the midpoint), missing
/// triangular facets are completed from the in-plane mesh tiling when
/// possible and otherwise split (at the transversal pierce point when an
/// edge pierces the facet, else at the centroid), and exterior tets are
/// carved away across non-constrained hull faces. Recovered constraint edges
/// and facets are both protected against later flips.
///
/// If recovery does not converge (see the module-level "Known limitation"
/// note), the function returns [`TetrahedralizationError::ConstraintRecoveryFailed`]
/// and never presents the unconstrained Delaunay mesh as a successful result.
///
/// `facet_markers`, when provided, is propagated through any Steiner
/// subdivision and applied to the recovered boundary sub-facets.
pub fn tetrahedralize_surface(
    surface_nodes: &[Point],
    surface_facets: &[[usize; 3]],
    facet_markers: Option<&[i32]>,
    config: &TetrahedralizeConfig,
) -> Result<Mesh, TetrahedralizationError> {
    tetrahedralize_surface_with_diagnostics(surface_nodes, surface_facets, facet_markers, config)
        .map(|result| result.mesh)
}

fn tetrahedralize_surface_with_diagnostics(
    surface_nodes: &[Point],
    surface_facets: &[[usize; 3]],
    facet_markers: Option<&[i32]>,
    config: &TetrahedralizeConfig,
) -> Result<TetrahedralizationResult, TetrahedralizationError> {
    validate_surface_input(surface_nodes, surface_facets, facet_markers)?;

    if surface_facets.is_empty() || !config.preserve_surface {
        let mut mesh = tetrahedralize_points(surface_nodes, config);
        apply_boundary_markers_in_detection_order(&mut mesh, facet_markers);
        let result = TetrahedralizationResult::from_mesh(mesh, None);
        return if result.validity.is_valid() {
            Ok(result)
        } else {
            Err(TetrahedralizationError::InvalidMesh {
                diagnostics: Box::new(result.validity),
            })
        };
    }

    let working_points = points_with_quality_steiner(surface_nodes, config);
    let run = run_constrained_delaunay(&working_points, surface_facets, facet_markers);
    if !run.diagnostics.is_complete() {
        return Err(TetrahedralizationError::ConstraintRecoveryFailed {
            diagnostics: Box::new(run.diagnostics),
        });
    }
    let elements = carve_exterior_tets(&run.nodes, run.tets, &run.recovered_facets);
    let (nodes, elements, recovered_facets) =
        compact_tet_mesh(run.nodes, elements, run.recovered_facets);
    let mut mesh = mesh_from_tets(nodes, elements);

    let marker_by_face: HashMap<[usize; 3], i32> = recovered_facets
        .iter()
        .map(|facet| (sorted3(facet.nodes), facet.marker))
        .collect();
    for boundary in &mut mesh.boundaries {
        if boundary.nodes.len() != 3 {
            continue;
        }
        let key = sorted3([boundary.nodes[0], boundary.nodes[1], boundary.nodes[2]]);
        if let Some(&marker) = marker_by_face.get(&key) {
            boundary.marker = marker;
        }
    }

    postprocess_mesh(&mut mesh, config);
    let recovery = build_recovery_diagnostics(
        surface_facets,
        &recovered_facets,
        &mesh
            .elements
            .iter()
            .map(|element| {
                let vertices = element.vertices();
                [vertices[0], vertices[1], vertices[2], vertices[3]]
            })
            .collect::<Vec<_>>(),
        RecoveryBuildState {
            rounds: run.diagnostics.rounds,
            steiner_points: run.diagnostics.steiner_points,
            operations: run.diagnostics.operations,
            boundary_only: true,
            converged: true,
            termination: ConstraintRecoveryTermination::Recovered,
        },
    );
    if !recovery.is_complete() {
        return Err(TetrahedralizationError::ConstraintRecoveryFailed {
            diagnostics: Box::new(recovery),
        });
    }
    let result = TetrahedralizationResult::from_mesh(mesh, Some(recovery));
    if result.validity.is_valid() {
        Ok(result)
    } else {
        Err(TetrahedralizationError::InvalidMesh {
            diagnostics: Box::new(result.validity),
        })
    }
}

/// Tetrahedralize a box domain with boundary markers
pub fn tetrahedralize_box(
    x_min: f64,
    x_max: f64,
    y_min: f64,
    y_max: f64,
    z_min: f64,
    z_max: f64,
    resolution: usize,
) -> Mesh {
    let mut points = Vec::new();

    let nx = resolution;
    let ny = resolution;
    let nz = resolution;

    let dx = (x_max - x_min) / nx as f64;
    let dy = (y_max - y_min) / ny as f64;
    let dz = (z_max - z_min) / nz as f64;

    for k in 0..=nz {
        for j in 0..=ny {
            for i in 0..=nx {
                let x = x_min + i as f64 * dx;
                let y = y_min + j as f64 * dy;
                let z = z_min + k as f64 * dz;
                points.push(Point::new_3d(x, y, z));
            }
        }
    }

    let config = TetrahedralizeConfig::default();
    let mut mesh = tetrahedralize_points(&points, &config);

    let tol_x = (x_max - x_min) / resolution as f64 * 0.5;
    let tol_y = (y_max - y_min) / resolution as f64 * 0.5;
    let tol_z = (z_max - z_min) / resolution as f64 * 0.5;

    mesh.set_boundary_condition(BoundaryType::Dirichlet, 1, |pts| {
        pts.iter().all(|p| (p.x - x_min).abs() < tol_x)
    });
    mesh.set_boundary_condition(BoundaryType::Dirichlet, 2, |pts| {
        pts.iter().all(|p| (p.x - x_max).abs() < tol_x)
    });
    mesh.set_boundary_condition(BoundaryType::Dirichlet, 3, |pts| {
        pts.iter().all(|p| (p.y - y_min).abs() < tol_y)
    });
    mesh.set_boundary_condition(BoundaryType::Dirichlet, 4, |pts| {
        pts.iter().all(|p| (p.y - y_max).abs() < tol_y)
    });
    mesh.set_boundary_condition(BoundaryType::Dirichlet, 5, |pts| {
        pts.iter().all(|p| (p.z - z_min).abs() < tol_z)
    });
    mesh.set_boundary_condition(BoundaryType::Dirichlet, 6, |pts| {
        pts.iter().all(|p| (p.z - z_max).abs() < tol_z)
    });

    mesh
}

/// Tetrahedralize a box domain with boundary markers and return quality diagnostics.
pub fn tetrahedralize_box_with_result(
    x_min: f64,
    x_max: f64,
    y_min: f64,
    y_max: f64,
    z_min: f64,
    z_max: f64,
    resolution: usize,
) -> TetrahedralizationResult {
    let mesh = tetrahedralize_box(x_min, x_max, y_min, y_max, z_min, z_max, resolution);
    TetrahedralizationResult::from_mesh(mesh, None)
}

/// Strict box tetrahedralization with checked bounds and resolution.
///
/// The legacy [`tetrahedralize_box`] helper remains infallible for source
/// compatibility. This entry point is intended for external configuration and
/// QA boundaries where a zero resolution or inverted/non-finite extent must be
/// reported instead of producing an empty or non-finite mesh.
pub fn tetrahedralize_box_checked(
    x_min: f64,
    x_max: f64,
    y_min: f64,
    y_max: f64,
    z_min: f64,
    z_max: f64,
    resolution: usize,
) -> Result<TetrahedralizationResult, TetrahedralizationError> {
    validate_box_input(x_min, x_max, y_min, y_max, z_min, z_max, resolution)?;
    let result =
        tetrahedralize_box_with_result(x_min, x_max, y_min, y_max, z_min, z_max, resolution);
    if result.validity.is_valid() && result.mesh.num_elements() > 0 {
        Ok(result)
    } else {
        Err(TetrahedralizationError::InvalidMesh {
            diagnostics: Box::new(result.validity),
        })
    }
}
