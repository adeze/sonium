//! Optional WebGPU coherent path-sum preview.
//!
//! This is deliberately a small, device-suitable preview primitive rather
//! than the production room solver. It evaluates a batch of already-generated
//! acoustic paths on the browser GPU. Room simulation continues to use the
//! validated CPU/WASM implementation until the complete geometry and BEM
//! kernels have a calibrated GPU counterpart.

use serde::Deserialize;
use wasm_bindgen::JsCast;
use wasm_bindgen::prelude::*;
use wasm_bindgen_futures::JsFuture;
use web_sys::window;

const MAX_PREVIEW_JSON_BYTES: usize = 4 * 1024 * 1024;
const MAX_PREVIEW_PATHS: usize = 4_096;
const MAX_PREVIEW_FREQUENCIES: usize = 4_096;

#[derive(Debug, Deserialize)]
struct PreviewInput {
    frequencies: Vec<f64>,
    distances: Vec<f64>,
    amplitudes: Vec<f64>,
    #[serde(default = "default_speed_of_sound")]
    speed_of_sound: f64,
}

fn default_speed_of_sound() -> f64 {
    343.0
}

const SHADER: &str = r#"
const PI: f32 = 3.141592653589793;

@group(0) @binding(0) var<storage, read> wavenumbers: array<f32>;
@group(0) @binding(1) var<storage, read> distances: array<f32>;
@group(0) @binding(2) var<storage, read> amplitudes: array<f32>;
@group(0) @binding(3) var<storage, read_write> result: array<vec2<f32>>;

@compute @workgroup_size(64)
fn main(@builtin(global_invocation_id) id: vec3<u32>) {
    let frequency_index = id.x;
    if (frequency_index >= arrayLength(&wavenumbers)) {
        return;
    }

    var sum = vec2<f32>(0.0, 0.0);
    for (var path_index = 0u; path_index < arrayLength(&distances); path_index++) {
        let phase = wavenumbers[frequency_index] * distances[path_index];
        let contribution = amplitudes[path_index] * vec2<f32>(cos(phase), sin(phase));
        sum += contribution;
    }
    result[frequency_index] = sum;
}
"#;

fn object(fields: &[(&str, JsValue)]) -> Result<js_sys::Object, JsValue> {
    let value = js_sys::Object::new();
    for (key, field) in fields {
        js_sys::Reflect::set(&value, &JsValue::from_str(key), field)?;
    }
    Ok(value)
}

fn call_method(receiver: &JsValue, name: &str, arguments: &[JsValue]) -> Result<JsValue, JsValue> {
    let method =
        js_sys::Reflect::get(receiver, &JsValue::from_str(name))?.dyn_into::<js_sys::Function>()?;
    let args = js_sys::Array::new();
    for argument in arguments {
        args.push(argument);
    }
    method.apply(receiver, &args)
}

async fn await_promise(value: JsValue) -> Result<JsValue, JsValue> {
    let promise = value.dyn_into::<js_sys::Promise>()?;
    JsFuture::from(promise).await
}

fn queue(device: &JsValue) -> Result<JsValue, JsValue> {
    js_sys::Reflect::get(device, &JsValue::from_str("queue"))
}

fn queue_write_buffer(device: &JsValue, buffer: &JsValue, values: &[f32]) -> Result<(), JsValue> {
    let typed = js_sys::Float32Array::from(values);
    call_method(
        &queue(device)?,
        "writeBuffer",
        &[
            buffer.clone(),
            JsValue::from_f64(0.0),
            typed.buffer().into(),
        ],
    )?;
    Ok(())
}

fn buffer(device: &JsValue, size: usize, usage: u32) -> Result<JsValue, JsValue> {
    let descriptor = object(&[
        ("size", JsValue::from_f64(size as f64)),
        ("usage", JsValue::from_f64(usage as f64)),
        ("mappedAtCreation", JsValue::FALSE),
    ])?;
    call_method(device, "createBuffer", &[descriptor.into()])
}

fn validate_input(input: &PreviewInput) -> Result<(), JsValue> {
    if input.frequencies.is_empty() || input.frequencies.len() > MAX_PREVIEW_FREQUENCIES {
        return Err(JsValue::from_str(
            "preview frequency count is out of bounds",
        ));
    }
    if input.distances.is_empty()
        || input.distances.len() > MAX_PREVIEW_PATHS
        || input.distances.len() != input.amplitudes.len()
    {
        return Err(JsValue::from_str(
            "preview paths must be non-empty, bounded, and aligned",
        ));
    }
    if !input.speed_of_sound.is_finite() || input.speed_of_sound <= 0.0 {
        return Err(JsValue::from_str(
            "preview speed_of_sound must be finite and positive",
        ));
    }
    if input
        .frequencies
        .iter()
        .any(|value| !value.is_finite() || *value <= 0.0)
        || input
            .distances
            .iter()
            .any(|value| !value.is_finite() || *value < 0.0)
        || input.amplitudes.iter().any(|value| !value.is_finite())
    {
        return Err(JsValue::from_str(
            "preview frequencies, distances, and amplitudes must be finite",
        ));
    }
    Ok(())
}

/// Evaluate a coherent batch of acoustic paths on WebGPU.
///
/// `distances` and `amplitudes` describe paths already generated by a room
/// model. The returned `complex_response` contains one `[real, imaginary]`
/// pair per requested frequency. This API returns an error when WebGPU is
/// unavailable; callers should use the normal CPU/WASM path in that case.
#[wasm_bindgen]
pub async fn compute_webgpu_preview(input_json: &str) -> Result<String, JsValue> {
    if input_json.len() > MAX_PREVIEW_JSON_BYTES {
        return Err(JsValue::from_str(
            "WebGPU preview JSON exceeds the 4 MiB limit",
        ));
    }
    let input: PreviewInput = serde_json::from_str(input_json)
        .map_err(|error| JsValue::from_str(&format!("invalid WebGPU preview JSON: {error}")))?;
    validate_input(&input)?;

    let window = window().ok_or_else(|| JsValue::from_str("WebGPU preview requires a browser"))?;
    let navigator = window.navigator();
    let gpu = js_sys::Reflect::get(navigator.as_ref(), &JsValue::from_str("gpu"))?;
    if gpu.is_null() || gpu.is_undefined() {
        return Err(JsValue::from_str("WebGPU is unavailable"));
    }
    let adapter = await_promise(call_method(&gpu, "requestAdapter", &[])?).await?;
    if adapter.is_null() || adapter.is_undefined() {
        return Err(JsValue::from_str("WebGPU adapter acquisition failed"));
    }
    let device = await_promise(call_method(&adapter, "requestDevice", &[])?).await?;

    let wavenumbers: Vec<f32> = input
        .frequencies
        .iter()
        .map(|frequency| (2.0 * std::f64::consts::PI * frequency / input.speed_of_sound) as f32)
        .collect();
    let distances: Vec<f32> = input.distances.iter().map(|value| *value as f32).collect();
    let amplitudes: Vec<f32> = input.amplitudes.iter().map(|value| *value as f32).collect();

    // GPUBufferUsage.STORAGE | COPY_DST = 0x0080 | 0x0008.
    let wavenumber_buffer = buffer(&device, wavenumbers.len() * 4, 0x0088)?;
    let distance_buffer = buffer(&device, distances.len() * 4, 0x0088)?;
    let amplitude_buffer = buffer(&device, amplitudes.len() * 4, 0x0088)?;
    queue_write_buffer(&device, &wavenumber_buffer, &wavenumbers)?;
    queue_write_buffer(&device, &distance_buffer, &distances)?;
    queue_write_buffer(&device, &amplitude_buffer, &amplitudes)?;

    // GPUBufferUsage.STORAGE | COPY_SRC = 0x0080 | 0x0004.
    let result_size = input.frequencies.len() * 8;
    let result_buffer = buffer(&device, result_size, 0x0084)?;
    // GPUBufferUsage.MAP_READ | COPY_DST = 0x0001 | 0x0008.
    let readback_buffer = buffer(&device, result_size, 0x0009)?;

    let shader = call_method(
        &device,
        "createShaderModule",
        &[object(&[("code", JsValue::from_str(SHADER))])?.into()],
    )?;
    let pipeline = call_method(
        &device,
        "createComputePipeline",
        &[object(&[
            ("layout", JsValue::from_str("auto")),
            (
                "compute",
                object(&[
                    ("module", shader),
                    ("entryPoint", JsValue::from_str("main")),
                ])?
                .into(),
            ),
        ])?
        .into()],
    )?;
    let layout = call_method(&pipeline, "getBindGroupLayout", &[JsValue::from_f64(0.0)])?;
    let entries = js_sys::Array::new();
    for (binding, resource) in [
        (0, wavenumber_buffer),
        (1, distance_buffer),
        (2, amplitude_buffer),
        (3, result_buffer.clone()),
    ] {
        entries.push(
            &object(&[
                ("binding", JsValue::from_f64(binding as f64)),
                ("resource", object(&[("buffer", resource)])?.into()),
            ])?
            .into(),
        );
    }
    let bind_group = call_method(
        &device,
        "createBindGroup",
        &[object(&[("layout", layout), ("entries", entries.into())])?.into()],
    )?;

    let encoder = call_method(&device, "createCommandEncoder", &[])?;
    let pass = call_method(&encoder, "beginComputePass", &[])?;
    call_method(&pass, "setPipeline", &[pipeline])?;
    call_method(&pass, "setBindGroup", &[JsValue::from_f64(0.0), bind_group])?;
    let workgroups = input.frequencies.len().div_ceil(64);
    call_method(
        &pass,
        "dispatchWorkgroups",
        &[JsValue::from_f64(workgroups as f64)],
    )?;
    call_method(&pass, "end", &[])?;
    call_method(
        &encoder,
        "copyBufferToBuffer",
        &[
            result_buffer,
            JsValue::from_f64(0.0),
            readback_buffer.clone(),
            JsValue::from_f64(0.0),
            JsValue::from_f64(result_size as f64),
        ],
    )?;
    let command = call_method(&encoder, "finish", &[])?;
    let command_array = js_sys::Array::new();
    command_array.push(&command);
    call_method(&queue(&device)?, "submit", &[command_array.into()])?;

    await_promise(call_method(
        &readback_buffer,
        "mapAsync",
        &[
            JsValue::from_f64(1.0),
            JsValue::from_f64(0.0),
            JsValue::from_f64(result_size as f64),
        ],
    )?)
    .await?;
    let mapped = call_method(&readback_buffer, "getMappedRange", &[])?;
    let values = js_sys::Float32Array::new(&mapped).to_vec();
    call_method(&readback_buffer, "unmap", &[])?;

    let complex_response: Vec<[f32; 2]> = values
        .as_chunks::<2>()
        .0
        .iter()
        .map(|pair| [pair[0], pair[1]])
        .collect();
    serde_json::to_string(&serde_json::json!({
        "backend": "webgpu",
        "frequencies": input.frequencies,
        "complex_response": complex_response,
    }))
    .map_err(|error| JsValue::from_str(&format!("WebGPU preview serialization failed: {error}")))
}
