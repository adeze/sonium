//! Native Gmsh consumers for bounded MeshLang projection meshes.
//!
//! The canonical projection evaluator remains backend-neutral. This module
//! provides the explicit product hand-off that was previously missing: a
//! validated `ProjectionMeshArtifact` becomes deterministic `.geo` source or
//! Python/Gmsh source. The generated programs contain only finite, bounded
//! triangles from the artifact; they never interpolate arbitrary source text
//! into a Gmsh expression.

use crate::error::CompileError;
use crate::projection::{ProjectionMeshArtifact, MAX_PROJECTION_MESH_ARTIFACT_BYTES};
use std::collections::BTreeMap;

/// Maximum generated native source size. This is intentionally below the
/// artifact JSON limit because every triangle expands to several Gmsh lines.
pub const MAX_NATIVE_PROJECTION_SOURCE_BYTES: usize = 16 * 1024 * 1024;

/// Deterministic native GEO/Python projection sources and size metadata.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NativeProjectionArtifacts {
    /// Gmsh `.geo` source containing a triangulated native surface.
    pub geo_source: String,
    /// Python source using the `gmsh.model.geo` API for the same surface.
    pub python_source: String,
    /// Number of artifact vertices emitted as Gmsh points.
    pub vertex_count: usize,
    /// Number of artifact triangles emitted as plane surfaces.
    pub triangle_count: usize,
}

/// Convert one validated projection artifact into native Gmsh sources.
pub fn projection_mesh_to_native(
    artifact: &ProjectionMeshArtifact,
) -> Result<NativeProjectionArtifacts, CompileError> {
    artifact.validate().map_err(|error| {
        CompileError::Unsupported(format!("invalid projection artifact: {error}"))
    })?;
    if artifact.mesh.vertices.len() > u32::MAX as usize
        || artifact.mesh.triangles.len() > u32::MAX as usize
    {
        return Err(CompileError::Unsupported(
            "projection artifact exceeds native Gmsh index limits".into(),
        ));
    }

    let mut geo = String::from(
        "// Generated by MeshLang native projection adapter\nSetFactory(\"OpenCASCADE\");\nMesh.Algorithm = 6;\n",
    );
    let mut python = String::from(
        "# Generated by MeshLang native projection adapter\nimport gmsh\n\ngmsh.initialize()\ngmsh.model.add(\"meshlang_projection\")\n",
    );

    for (index, point) in artifact.mesh.vertices.iter().enumerate() {
        let id = index + 1;
        geo.push_str(&format!(
            "Point({id}) = {{{:.17}, {:.17}, {:.17}}};\n",
            point[0], point[1], point[2]
        ));
        python.push_str(&format!(
            "p{id} = gmsh.model.geo.addPoint({:.17}, {:.17}, {:.17})\n",
            point[0], point[1], point[2]
        ));
    }

    // One deterministic line per undirected artifact edge. Reusing lines
    // keeps adjacent triangles conforming and makes output independent of
    // hash-map iteration order.
    let mut edges = BTreeMap::<(u32, u32), u32>::new();
    for triangle in &artifact.mesh.triangles {
        for &(from, to) in &[
            (triangle[0], triangle[1]),
            (triangle[1], triangle[2]),
            (triangle[2], triangle[0]),
        ] {
            let key = if from < to { (from, to) } else { (to, from) };
            if !edges.contains_key(&key) {
                let line_id = u32::try_from(edges.len() + 1).map_err(|_| {
                    CompileError::Unsupported("projection edge index overflow".into())
                })?;
                edges.insert(key, line_id);
            }
        }
    }
    for (&(from, to), &line_id) in &edges {
        geo.push_str(&format!(
            "Line({line_id}) = {{{}, {}}};\n",
            from + 1,
            to + 1
        ));
        python.push_str(&format!(
            "l{line_id} = gmsh.model.geo.addLine(p{}, p{})\n",
            from + 1,
            to + 1
        ));
    }

    for (index, triangle) in artifact.mesh.triangles.iter().enumerate() {
        let loop_id = index + 1;
        let oriented = triangle
            .iter()
            .zip(triangle.iter().cycle().skip(1))
            .map(|(&from, &to)| {
                let key = if from < to { (from, to) } else { (to, from) };
                let line_id = edges[&key];
                if from < to {
                    line_id.to_string()
                } else {
                    format!("-{line_id}")
                }
            })
            .collect::<Vec<_>>();
        let oriented_csv = oriented.join(", ");
        geo.push_str(&format!(
            "Line Loop({loop_id}) = {{{oriented_csv}}};\nPlane Surface({loop_id}) = {{{loop_id}}};\n"
        ));
        let python_lines = triangle
            .iter()
            .zip(triangle.iter().cycle().skip(1))
            .map(|(&from, &to)| {
                let key = if from < to { (from, to) } else { (to, from) };
                let line_id = edges[&key];
                if from < to {
                    format!("l{line_id}")
                } else {
                    format!("-l{line_id}")
                }
            })
            .collect::<Vec<_>>();
        python.push_str(&format!(
            "ll{loop_id} = gmsh.model.geo.addCurveLoop([{}])\ns{loop_id} = gmsh.model.geo.addPlaneSurface([ll{loop_id}])\n",
            python_lines.join(", ")
        ));
    }

    if !artifact.mesh.triangles.is_empty() {
        let surfaces = (1..=artifact.mesh.triangles.len())
            .map(|id| id.to_string())
            .collect::<Vec<_>>()
            .join(", ");
        geo.push_str(&format!(
            "Physical Surface(\"MeshLangProjection\") = {{{surfaces}}};\n"
        ));
        python.push_str(&format!(
            "gmsh.model.geo.synchronize()\ngmsh.model.addPhysicalGroup(2, [{}], 1)\ngmsh.model.mesh.generate(2)\n",
            (1..=artifact.mesh.triangles.len())
                .map(|id| format!("s{id}"))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    } else {
        // Gmsh accepts an empty geometry only after synchronization; retain a
        // valid executable Python program for empty but valid artifacts.
        python.push_str("gmsh.model.geo.synchronize()\n");
    }
    python.push_str("gmsh.finalize()\n");

    if geo.len() > MAX_NATIVE_PROJECTION_SOURCE_BYTES
        || python.len() > MAX_NATIVE_PROJECTION_SOURCE_BYTES
    {
        return Err(CompileError::Unsupported(format!(
            "native projection source exceeds {MAX_NATIVE_PROJECTION_SOURCE_BYTES} bytes"
        )));
    }
    // Keep the source and artifact budgets visible at the API boundary. This
    // is defensive if the artifact validator's limit changes independently.
    if geo.len() > MAX_PROJECTION_MESH_ARTIFACT_BYTES * 2
        || python.len() > MAX_PROJECTION_MESH_ARTIFACT_BYTES * 2
    {
        return Err(CompileError::Unsupported(
            "native projection source exceeds artifact-derived budget".into(),
        ));
    }

    Ok(NativeProjectionArtifacts {
        geo_source: geo,
        python_source: python,
        vertex_count: artifact.mesh.vertices.len(),
        triangle_count: artifact.mesh.triangles.len(),
    })
}

/// Build native GEO/Python sources directly from MeshLang source.
pub fn compile_projection_native_artifacts(
    source: &str,
    filename: &str,
    projection_name: &str,
    bounds: [[f64; 3]; 2],
    cells: [usize; 3],
    tolerance: f64,
) -> Result<NativeProjectionArtifacts, CompileError> {
    let artifact = crate::compile_projection_mesh_artifact(
        source,
        filename,
        projection_name,
        bounds,
        cells,
        tolerance,
    )?;
    projection_mesh_to_native(&artifact)
}
