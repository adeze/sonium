//! Native Gmsh volume remeshing sources for closed MeshLang projection meshes.
//!
//! The regular native projection adapter emits a surface mesh. Product hosts
//! that need a body-fitted volume must not guess whether that surface is
//! closed or synthesize a volume with backend-specific defaults. This module
//! admits only one connected, consistently oriented, closed triangle shell
//! and emits deterministic GEO/Python sources for a single tetrahedral volume.

use crate::error::CompileError;
use crate::projection::ProjectionMeshArtifact;
use crate::projection_native::MAX_NATIVE_PROJECTION_SOURCE_BYTES;
use std::collections::{BTreeMap, BTreeSet, VecDeque};

/// Deterministic native volume-remeshing sources and artifact metadata.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NativeProjectionVolumeArtifacts {
    /// Gmsh `.geo` source that creates one volume from the closed shell.
    pub geo_source: String,
    /// Python source using the `gmsh.model.geo` API for the same volume.
    pub python_source: String,
    /// Number of artifact vertices emitted as Gmsh points.
    pub vertex_count: usize,
    /// Number of artifact triangles emitted as plane surfaces.
    pub triangle_count: usize,
    /// Number of volume entities emitted (always one for this contract).
    pub volume_count: usize,
}

/// Convert a validated closed projection shell into native volume sources.
pub fn projection_mesh_to_native_volume(
    artifact: &ProjectionMeshArtifact,
) -> Result<NativeProjectionVolumeArtifacts, CompileError> {
    artifact.validate().map_err(|error| {
        CompileError::Unsupported(format!("invalid projection artifact: {error}"))
    })?;
    let triangles = &artifact.mesh.triangles;
    if triangles.is_empty() {
        return Err(CompileError::Unsupported(
            "native volume projection requires a non-empty closed triangle shell".into(),
        ));
    }

    let mut edge_uses: BTreeMap<(usize, usize), Vec<(usize, bool)>> = BTreeMap::new();
    let mut triangle_neighbors = vec![Vec::new(); triangles.len()];
    for (triangle_index, triangle) in triangles.iter().enumerate() {
        for edge_index in 0..3 {
            let from = triangle[edge_index] as usize;
            let to = triangle[(edge_index + 1) % 3] as usize;
            let key = (from.min(to), from.max(to));
            let forward = from < to;
            edge_uses
                .entry(key)
                .or_default()
                .push((triangle_index, forward));
        }
    }
    for (edge, uses) in &edge_uses {
        if uses.len() != 2 {
            return Err(CompileError::Unsupported(format!(
                "native volume projection requires every shell edge exactly twice; edge {edge:?} has {} uses",
                uses.len()
            )));
        }
        if uses[0].1 == uses[1].1 {
            return Err(CompileError::Unsupported(format!(
                "native volume projection shell has inconsistent orientation on edge {edge:?}"
            )));
        }
        triangle_neighbors[uses[0].0].push(uses[1].0);
        triangle_neighbors[uses[1].0].push(uses[0].0);
    }

    let mut seen = BTreeSet::new();
    let mut queue = VecDeque::from([0usize]);
    while let Some(triangle) = queue.pop_front() {
        if !seen.insert(triangle) {
            continue;
        }
        queue.extend(triangle_neighbors[triangle].iter().copied());
    }
    if seen.len() != triangles.len() {
        return Err(CompileError::Unsupported(
            "native volume projection requires one connected closed shell".into(),
        ));
    }

    let mut edges = BTreeMap::<(usize, usize), u32>::new();
    for edge in edge_uses.keys().copied() {
        let line_id = u32::try_from(edges.len() + 1)
            .map_err(|_| CompileError::Unsupported("native Gmsh line index overflow".into()))?;
        edges.insert(edge, line_id);
    }

    let mut geo = "// Generated by MeshLang native volume projection adapter\n".to_owned()
        + "SetFactory(\"OpenCASCADE\");\nMesh.Algorithm = 6;\n";
    let mut python = "# Generated by MeshLang native volume projection adapter\n".to_owned()
        + "import gmsh\n\ngmsh.initialize()\ngmsh.model.add(\"meshlang_projection_volume\")\n";
    for (index, point) in artifact.mesh.vertices.iter().enumerate() {
        let id = index + 1;
        geo.push_str(&format!(
            "Point({id}) = {{{:.17}, {:.17}, {:.17}, 1.0}};\n",
            point[0], point[1], point[2]
        ));
        python.push_str(&format!(
            "p{id} = gmsh.model.geo.addPoint({:.17}, {:.17}, {:.17}, 1.0)\n",
            point[0], point[1], point[2]
        ));
    }
    for (&(from, to), &line_id) in &edges {
        geo.push_str(&format!(
            "Line({line_id}) = {{{}, {}}};\n",
            from + 1,
            to + 1
        ));
        python.push_str(&format!(
            "l{line_id} = gmsh.model.geo.addLine(p{}, p{})\n",
            from + 1,
            to + 1
        ));
    }

    let mut surface_ids = Vec::with_capacity(triangles.len());
    for (triangle_index, triangle) in triangles.iter().enumerate() {
        let surface_id = triangle_index + 1;
        let oriented_lines = (0..3)
            .map(|edge_index| {
                let from = triangle[edge_index] as usize;
                let to = triangle[(edge_index + 1) % 3] as usize;
                let line_id = edges[&(from.min(to), from.max(to))];
                if from < to {
                    line_id.to_string()
                } else {
                    format!("-{line_id}")
                }
            })
            .collect::<Vec<_>>();
        let line_csv = oriented_lines.join(", ");
        geo.push_str(&format!(
            "Line Loop({surface_id}) = {{{line_csv}}};\nPlane Surface({surface_id}) = {{{surface_id}}};\n"
        ));
        let python_lines = oriented_lines
            .iter()
            .map(|line| {
                if let Some(line_id) = line.strip_prefix('-') {
                    format!("-l{line_id}")
                } else {
                    format!("l{line}")
                }
            })
            .collect::<Vec<_>>();
        python.push_str(&format!(
            "ll{surface_id} = gmsh.model.geo.addCurveLoop([{}])\ns{surface_id} = gmsh.model.geo.addPlaneSurface([ll{surface_id}])\n",
            python_lines.join(", ")
        ));
        surface_ids.push(surface_id);
    }

    let surface_csv = surface_ids
        .iter()
        .map(ToString::to_string)
        .collect::<Vec<_>>()
        .join(", ");
    geo.push_str(&format!(
        "Surface Loop(1) = {{{surface_csv}}};\nVolume(1) = {{1}};\nPhysical Surface(\"MeshLangProjectionSurface\") = {{{surface_csv}}};\nPhysical Volume(\"MeshLangProjectionVolume\") = {{1}};\nMesh 3;\n"
    ));
    python.push_str(&format!(
        "gmsh.model.geo.synchronize()\nsl1 = gmsh.model.geo.addSurfaceLoop([{}])\nv1 = gmsh.model.geo.addVolume([sl1])\ngmsh.model.geo.synchronize()\ngmsh.model.addPhysicalGroup(2, [{}], 1)\ngmsh.model.addPhysicalGroup(3, [v1], 2)\ngmsh.model.mesh.generate(3)\ngmsh.finalize()\n",
        surface_ids
            .iter()
            .map(|id| format!("s{id}"))
            .collect::<Vec<_>>()
            .join(", "),
        surface_ids
            .iter()
            .map(|id| format!("s{id}"))
            .collect::<Vec<_>>()
            .join(", ")
    ));

    if geo.len() > MAX_NATIVE_PROJECTION_SOURCE_BYTES
        || python.len() > MAX_NATIVE_PROJECTION_SOURCE_BYTES
    {
        return Err(CompileError::Unsupported(format!(
            "native volume projection source exceeds {MAX_NATIVE_PROJECTION_SOURCE_BYTES}-byte limit"
        )));
    }

    Ok(NativeProjectionVolumeArtifacts {
        geo_source: geo,
        python_source: python,
        vertex_count: artifact.mesh.vertices.len(),
        triangle_count: triangles.len(),
        volume_count: 1,
    })
}

/// Compile a MeshLang projection and lower it directly to native volume
/// sources. The same closed-shell admission is applied after projection.
pub fn compile_projection_native_volume_artifacts(
    source: &str,
    filename: &str,
    projection_name: &str,
    bounds: [[f64; 3]; 2],
    cells: [usize; 3],
    tolerance: f64,
) -> Result<NativeProjectionVolumeArtifacts, CompileError> {
    let artifact = crate::compile_projection_mesh_artifact(
        source,
        filename,
        projection_name,
        bounds,
        cells,
        tolerance,
    )?;
    projection_mesh_to_native_volume(&artifact)
}
