//! Triplet (COO) sparse matrix format
//!
//! Generic coordinate-format sparse matrix accumulator. Stores `(row, col, value)`
//! triplets that are summed and sorted during conversion to CSR.
//!
//! Used by FEM assembly to accumulate element-level contributions before
//! converting to [`CsrMatrix`] for solving.

use crate::CsrMatrix;
use sonium_solvers_core::traits::ComplexField;

/// Sparse matrix in triplet (COO) format.
///
/// Stores `(row, col, value)` triplets. Duplicate entries at the same position
/// are summed during conversion to CSR.
#[derive(Debug, Clone)]
pub struct TripletMatrix<T> {
    pub rows: Vec<usize>,
    pub cols: Vec<usize>,
    pub values: Vec<T>,
    pub num_rows: usize,
    pub num_cols: usize,
}

impl<T> TripletMatrix<T> {
    /// Number of stored triplets (including duplicates).
    pub fn nnz(&self) -> usize {
        self.values.len()
    }
}

impl<T: Copy + Default + std::ops::AddAssign + Send + Sync> TripletMatrix<T> {
    /// Create an empty triplet matrix with the given dimensions.
    pub fn new(num_rows: usize, num_cols: usize) -> Self {
        Self {
            rows: Vec::new(),
            cols: Vec::new(),
            values: Vec::new(),
            num_rows,
            num_cols,
        }
    }

    /// Create with pre-allocated capacity.
    pub fn with_capacity(num_rows: usize, num_cols: usize, capacity: usize) -> Self {
        Self {
            rows: Vec::with_capacity(capacity),
            cols: Vec::with_capacity(capacity),
            values: Vec::with_capacity(capacity),
            num_rows,
            num_cols,
        }
    }

    /// Add a triplet entry. Duplicate `(row, col)` entries will be summed in CSR conversion.
    #[inline]
    pub fn push(&mut self, row: usize, col: usize, value: T) {
        self.rows.push(row);
        self.cols.push(col);
        self.values.push(value);
    }
}

impl<T: ComplexField> TripletMatrix<T> {
    /// Convert to CSR format, summing duplicate entries.
    ///
    /// This compatibility method preserves the historical infallible API.
    /// New callers accepting externally populated triplet buffers should use
    /// [`Self::try_to_csr`] so malformed input becomes a typed error.
    pub fn to_csr(&self) -> CsrMatrix<T> {
        self.try_to_csr()
            .unwrap_or_else(|error| panic!("invalid triplet CSR conversion: {error}"))
    }

    /// Checked conversion to CSR, summing duplicate entries and sorting by
    /// row/column.
    ///
    /// The triplet fields are public for assembly compatibility, so callers
    /// may provide mismatched buffers or out-of-range coordinates. Duplicate
    /// coalescing is delegated to the checked CSR constructor, which also
    /// rejects non-finite values generated by an overflowing sum.
    pub fn try_to_csr(&self) -> Result<CsrMatrix<T>, sonium_solvers_core::traits::SolverError> {
        if self.rows.len() != self.cols.len() {
            return Err(
                sonium_solvers_core::traits::SolverError::DimensionMismatch {
                    expected: self.rows.len(),
                    got: self.cols.len(),
                },
            );
        }
        if self.rows.len() != self.values.len() {
            return Err(
                sonium_solvers_core::traits::SolverError::DimensionMismatch {
                    expected: self.rows.len(),
                    got: self.values.len(),
                },
            );
        }

        let triplets = self
            .rows
            .iter()
            .copied()
            .zip(self.cols.iter().copied())
            .zip(self.values.iter().copied())
            .map(|((row, col), value)| (row, col, value))
            .collect();
        CsrMatrix::try_from_triplets(self.num_rows, self.num_cols, triplets)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_triplet_to_csr_f64() {
        let mut t = TripletMatrix::new(3, 3);
        t.push(0, 0, 1.0);
        t.push(0, 2, 2.0);
        t.push(1, 1, 3.0);
        t.push(2, 0, 4.0);
        t.push(2, 2, 5.0);

        let csr = t.to_csr();
        assert_eq!(csr.num_rows, 3);
        assert_eq!(csr.num_cols, 3);
        assert_eq!(csr.nnz(), 5);
    }

    #[test]
    fn test_triplet_duplicates_summed() {
        let mut t = TripletMatrix::new(2, 2);
        t.push(0, 0, 1.0);
        t.push(0, 0, 2.0); // duplicate
        t.push(1, 1, 3.0);

        let csr = t.to_csr();
        assert_eq!(csr.nnz(), 2);
        // (0,0) should be 1+2 = 3
        let val: f64 = csr
            .row_entries(0)
            .find(|(j, _)| *j == 0)
            .map(|(_, v)| v)
            .unwrap();
        assert!((val - 3.0).abs() < 1e-14);
    }

    #[test]
    fn test_triplet_to_csr_complex64() {
        use num_complex::Complex64;

        let mut t = TripletMatrix::new(2, 2);
        t.push(0, 0, Complex64::new(1.0, 2.0));
        t.push(0, 1, Complex64::new(3.0, 0.0));
        t.push(1, 0, Complex64::new(0.0, 4.0));
        t.push(1, 1, Complex64::new(5.0, 6.0));

        let csr = t.to_csr();
        assert_eq!(csr.num_rows, 2);
        assert_eq!(csr.nnz(), 4);
    }

    #[test]
    fn test_triplet_empty() {
        let t: TripletMatrix<f64> = TripletMatrix::new(5, 5);
        let csr = t.to_csr();
        assert_eq!(csr.num_rows, 5);
        assert_eq!(csr.nnz(), 0);
    }

    #[test]
    fn checked_triplet_conversion_rejects_malformed_storage() {
        let malformed_lengths = TripletMatrix {
            rows: vec![0],
            cols: Vec::new(),
            values: vec![1.0_f64],
            num_rows: 1,
            num_cols: 1,
        };
        assert!(matches!(
            malformed_lengths.try_to_csr(),
            Err(
                sonium_solvers_core::traits::SolverError::DimensionMismatch {
                    expected: 1,
                    got: 0,
                }
            )
        ));

        let out_of_range = TripletMatrix {
            rows: vec![1],
            cols: vec![0],
            values: vec![1.0_f64],
            num_rows: 1,
            num_cols: 1,
        };
        assert!(matches!(
            out_of_range.try_to_csr(),
            Err(sonium_solvers_core::traits::SolverError::OperationFailed {
                operation: "CSR triplet construction",
                ..
            })
        ));

        let non_finite = TripletMatrix {
            rows: vec![0],
            cols: vec![0],
            values: vec![f64::NAN],
            num_rows: 1,
            num_cols: 1,
        };
        assert!(non_finite.try_to_csr().is_err());
    }

    #[test]
    fn checked_triplet_conversion_rejects_duplicate_sum_overflow() {
        let overflowing = TripletMatrix {
            rows: vec![0, 0],
            cols: vec![0, 0],
            values: vec![f64::MAX, f64::MAX],
            num_rows: 1,
            num_cols: 1,
        };
        assert!(matches!(
            overflowing.try_to_csr(),
            Err(sonium_solvers_core::traits::SolverError::OperationFailed {
                operation: "CSR triplet construction",
                ref reason,
            }) if reason.contains("duplicate coalescing generated non-finite")
        ));
    }
}
